// Writes src/generated/<slug>.stories.tsx with one story per example in @machine-ui/examples.
// Runs before `storybook` and `test`, so every example gets a render + axe check. The registry is
// loaded through Vite (it uses import.meta.glob and TSX), so names come from the same source as the docs.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import type { ComponentDoc } from '@machine-ui/examples';

const outDir = fileURLToPath(new URL('../src/generated/', import.meta.url));

const CATEGORY_TITLES: Record<ComponentDoc['category'], string> = {
  forms: 'Forms',
  overlays: 'Overlays',
  navigation: 'Navigation',
  data: 'Data display',
  feedback: 'Feedback',
  layout: 'Layout',
  ai: 'AI elements',
};

const pascal = (s: string) =>
  s
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .trim()
    .split(' ')
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join('');

const server = await createServer({
  // Root at this app so workspace dependencies resolve regardless of the working directory.
  root: fileURLToPath(new URL('..', import.meta.url)),
  configFile: false,
  appType: 'custom',
  logLevel: 'error',
  server: { middlewareMode: true },
});
let docs: ComponentDoc[];
try {
  ({ COMPONENT_DOCS: docs } = (await server.ssrLoadModule('@machine-ui/examples')) as { COMPONENT_DOCS: ComponentDoc[] });
} finally {
  await server.close();
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

let total = 0;
for (const doc of docs) {
  if (doc.examples.length === 0) throw new Error(`${doc.slug} has no examples`);
  const used = new Set<string>();
  const stories = doc.examples.map((example, i) => {
    let id = pascal(example.name);
    if (/^\d/.test(id)) id = `Example${id}`;
    while (used.has(id)) id += i;
    used.add(id);
    return `export const ${id}: Story = { name: ${JSON.stringify(example.name)}, render: () => <>{doc.examples[${i}]!.render()}</> };`;
  });

  writeFileSync(
    `${outDir}${doc.slug}.stories.tsx`,
    `// Generated by scripts/gen-stories.ts from @machine-ui/examples. Do not edit.
import type { Meta, StoryObj } from '@storybook/react-vite';
import doc from '@machine-ui/examples/components/${doc.slug}.tsx';

const meta = {
  title: ${JSON.stringify(`Examples/${CATEGORY_TITLES[doc.category]}/${doc.name}`)},
  parameters: { docs: { description: { component: doc.description } } },
} satisfies Meta;

export default meta;
type Story = StoryObj<typeof meta>;

${stories.join('\n')}
`,
  );
  total += doc.examples.length;
}
console.log(`generated ${total} example stories for ${docs.length} components`);
