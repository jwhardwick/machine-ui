// Writes src/generated/<slug>.stories.tsx with one story per example in @machine-ui/examples.
// Runs before `storybook` and `test`, so every example gets a render + axe check.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const examplesDir = fileURLToPath(new URL('../../../packages/examples/src/components/', import.meta.url));
const outDir = fileURLToPath(new URL('../src/generated/', import.meta.url));

const CATEGORY_TITLES: Record<string, string> = {
  forms: 'Forms',
  overlays: 'Overlays',
  navigation: 'Navigation',
  data: 'Data display',
  feedback: 'Feedback',
  layout: 'Layout',
  ai: 'AI elements',
};

const pascal = (s: string) =>
  s
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .trim()
    .split(' ')
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join('');

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

let total = 0;
for (const file of readdirSync(examplesDir).filter((f) => f.endsWith('.tsx'))) {
  const source = readFileSync(examplesDir + file, 'utf8');
  const slug = file.replace(/\.tsx$/, '');
  const name = /^\s{2}name: '([^']+)'/m.exec(source)?.[1];
  const category = /^\s{2}category: '(\w+)'/m.exec(source)?.[1];
  // Example entries sit at four spaces of indent inside `examples: [`.
  const examplesBlock = source.slice(source.indexOf('examples: ['));
  const names = [...examplesBlock.matchAll(/^ {4}\{\s*name: '([^']+)'/gm)].map((m) => m[1]!);
  if (!name || !category || names.length === 0) throw new Error(`Could not read examples from ${file}`);

  const used = new Set<string>();
  const stories = names.map((exampleName, i) => {
    let id = pascal(exampleName);
    if (/^\d/.test(id)) id = `Example${id}`;
    while (used.has(id)) id += i;
    used.add(id);
    return `export const ${id}: Story = { name: ${JSON.stringify(exampleName)}, render: () => <>{doc.examples[${i}]!.render()}</> };`;
  });

  writeFileSync(
    `${outDir}${slug}.stories.tsx`,
    `// Generated by scripts/gen-stories.ts from @machine-ui/examples. Do not edit.
import type { Meta, StoryObj } from '@storybook/react-vite';
import doc from '@machine-ui/examples/components/${slug}.tsx';

const meta = {
  title: 'Examples/${CATEGORY_TITLES[category] ?? category}/${name}',
  parameters: { docs: { description: { component: doc.description } } },
} satisfies Meta;

export default meta;
type Story = StoryObj<typeof meta>;

${stories.join('\n')}
`,
  );
  total += names.length;
}
console.log(`generated ${total} example stories`);
