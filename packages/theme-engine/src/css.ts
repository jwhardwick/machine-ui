import type { ThemeSeed, ThemeTokens } from '@machine-ui/tokens';
import { generateTheme } from './generate.ts';

const declarations = (tokens: Record<string, string>, indent = '  ') =>
  Object.entries(tokens)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join('\n');

/**
 * Serialise tokens to CSS. Light values sit on `selector`; dark values apply when the
 * element has `.dark` / `data-mode="dark"`, or (for scoped selectors) an ancestor does.
 */
export function themeToCss(tokens: ThemeTokens, opts: { selector?: string } = {}): string {
  const sel = opts.selector ?? ':root';
  const darkSelectors = [`${sel}.dark`, `${sel}[data-mode="dark"]`];
  if (sel !== ':root') darkSelectors.push(`:where(.dark, [data-mode="dark"]) ${sel}:not([data-mode="light"])`);

  return [
    `${sel} {\n${declarations({ ...tokens.shared, ...tokens.light })}\n}`,
    `${darkSelectors.join(', ')} {\n${declarations(tokens.dark)}\n}`,
    `@media (prefers-reduced-motion: reduce) {\n  ${sel} {\n${declarations(
      { 'motion-fast': '0ms', 'motion-normal': '0ms', 'motion-slow': '0ms' },
      '    ',
    )}\n  }\n}`,
  ].join('\n\n');
}

/** Contents of `@machine-ui/tokens/css/themes/<name>.css`. */
export function referenceThemeCss(seed: ThemeSeed): string {
  return `/* Generated by @machine-ui/theme-engine (pnpm --filter @machine-ui/theme-engine build:css). Do not edit. */\n\n${themeToCss(generateTheme(seed))}\n`;
}
