// The light entry for the docs site: enough to list every component and screen, with example code,
// example source and screens loaded on demand so each page downloads only what it shows.
import { lazy, type ComponentType } from 'react';
import catalog from './catalog.json';
import type { ScreenDoc } from './screens/index.ts';
import { SCREEN_META } from './screens/meta.ts';
import type { ComponentDoc, ComponentMeta } from './types.ts';

export * from './types.ts';
export type { ScreenDoc } from './screens/index.ts';

/** Every documented component without its examples, alphabetical. Generated by `pnpm docs:build`. */
export const COMPONENTS = catalog as ComponentMeta[];

export function getMeta(slug: string): ComponentMeta | undefined {
  return COMPONENTS.find((meta) => meta.slug === slug);
}

export function installCommand(slug: string): string {
  return `npx shadcn@latest add ${getMeta(slug)?.install.join(' ') ?? ''}`;
}

const docModules = import.meta.glob<{ default: ComponentDoc }>('./components/*.tsx');
const sourceModules = import.meta.glob<string>('./components/*.tsx', { query: '?raw', import: 'default' });

/** Memoises a loader per slug, so React's `use` gets the same promise on every render. */
function perSlug<T>(load: (slug: string) => Promise<T>): (slug: string) => Promise<T> {
  const cache = new Map<string, Promise<T>>();
  return (slug) => {
    let promise = cache.get(slug);
    if (!promise) {
      promise = load(slug);
      cache.set(slug, promise);
    }
    return promise;
  };
}

/** A component's docs entry with its examples. */
export const loadDoc = perSlug(async (slug) => {
  const load = docModules[`./components/${slug}.tsx`];
  if (!load) throw new Error(`No examples for "${slug}"`);
  return (await load()).default;
});

/** Source of a component's example module, for the docs code view. */
export const loadSource = perSlug(async (slug) => {
  const load = sourceModules[`./components/${slug}.tsx`];
  if (!load) throw new Error(`No examples for "${slug}"`);
  return load();
});

const SCREEN_COMPONENTS: Record<string, ComponentType> = {
  chat: lazy(() => import('./screens/chat.tsx').then((m) => ({ default: m.ChatScreen }))),
  dashboard: lazy(() => import('./screens/dashboard.tsx').then((m) => ({ default: m.DashboardScreen }))),
  settings: lazy(() => import('./screens/settings.tsx').then((m) => ({ default: m.SettingsScreen }))),
};

/** The example screens. Each `Component` loads on first render, so render it inside Suspense. */
export const SCREENS: ScreenDoc[] = SCREEN_META.map((meta) => ({ ...meta, Component: SCREEN_COMPONENTS[meta.slug]! }));
